type DictKey = keyof (typeof dict)['en'];

interface LangCtx {
  lang: Lang;
  dir: 'ltr' | 'rtl';
  t: (k: DictKey) => string;
  toggle: () => void;
}

const Ctx = createContext<LangCtx | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem('augmentoria-lang');
      return saved === 'ar' ? 'ar' : 'en';
    } catch {
      return 'en';
    }
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    try {
      localStorage.setItem('augmentoria-lang', lang);
    } catch {
      // Language preference is optional; keep the current session working if storage is unavailable.
    }
  }, [lang]);

  const value: LangCtx = {
    lang,
    dir: lang === 'ar' ? 'rtl' : 'ltr',
    t: (k) => dict[lang][k],
    toggle: () => setLang((l) => (l === 'en' ? 'ar' : 'en'))
  };

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useLang() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error('useLang must be used inside LangProvider');
  return ctx;
}
